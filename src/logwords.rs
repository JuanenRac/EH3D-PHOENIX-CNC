#[cfg(test)]
mod tests {
    use super::*;

    fn holes(s: &str) -> Vec<usize> {
        (0..10)
            .filter(|i| s.contains(&format!("{{{i}}}")))
            .collect()
    }

    #[test]
    fn every_message_of_the_log_is_written_in_the_eight_languages_with_the_same_holes() {
        for (n, m) in Lg::ALL.into_iter().enumerate() {
            let row = m.row();
            assert_eq!(Lg::ALL.iter().filter(|o| **o == m).count(), 1, "{n}");
            for (i, s) in row.iter().enumerate() {
                assert!(!s.trim().is_empty(), "{m:?} is empty in {}", LANGS[i]);
                assert_eq!(holes(s), holes(row[0]), "{m:?} in {}", LANGS[i]);
            }
            // Japanese and Chinese are never the English text, apart from a line that is only holes
            if !matches!(m, Lg::MapLine) {
                assert_ne!(row[5], row[0], "{m:?}");
                assert_ne!(row[6], row[0], "{m:?}");
            }
        }
    }

    #[test]
    fn the_holes_are_filled_and_an_unknown_language_or_word_stays_readable() {
        assert_eq!(
            say("de", Lg::ResumedAt, &["7"]),
            "Programm ab Zeile 7 wieder aufgenommen"
        );
        assert_eq!(
            say("xx", Lg::ResumedAt, &["7"]),
            "program resumed at line 7"
        );
        assert_eq!(
            say("pt-PT", Lg::Estop, &[] as &[&str]),
            text("pt", Lg::Estop)
        );
        assert_eq!(what("es", "jog"), "desplazamiento manual");
        assert_eq!(what("es", "G28.1"), "G28.1");
        assert_eq!(job_state("fr", "running"), "en cours");
        assert_eq!(job_state("fr", "something new"), "something new");
    }
}
