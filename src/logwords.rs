fn column(lang: &str) -> usize {
    let code = lang.trim().split('-').next().unwrap_or("");
    LANGS
        .iter()
        .position(|l| l.eq_ignore_ascii_case(code))
        .unwrap_or(0)
}

/// The message with `{0}`, `{1}`, ... replaced by the arguments, in the language of the code (English for one the tables do not have).
pub fn say<S: AsRef<str>>(lang: &str, m: Lg, args: &[S]) -> String {
    let mut out = m.row()[column(lang)].to_string();
    for (i, a) in args.iter().enumerate().rev() {
        out = out.replace(&format!("{{{i}}}"), a.as_ref());
    }
    out
}

/// A message with no holes.
pub fn text(lang: &str, m: Lg) -> &'static str {
    m.row()[column(lang)]
}

